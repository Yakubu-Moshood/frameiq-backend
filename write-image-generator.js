const fs = require('fs');
const p = '/data/pipeline/surface-image-generator.cjs';

const lines = [];
lines.push("'use strict';");
lines.push("");
lines.push("require('dotenv').config();");
lines.push("");
lines.push("const fs2   = require('fs');");
lines.push("const path  = require('path');");
lines.push("const https = require('https');");
lines.push("const { getChannelConfigByLabel } = require('./config-reader.cjs');");
lines.push("const { createRouter } = require('./providers/provider-router.cjs');");
lines.push("const sdxl = require('./providers/image/sdxl.cjs');");
lines.push("");
lines.push("const OPENAI_KEY = process.env.OPENAI_API_KEY;");
lines.push("const SIZE       = '1536x1024';");
lines.push("const SLEEP_MS   = 2000;");
lines.push("const SLEEP_FAIL = 5000;");
lines.push("");
lines.push("function log(msg) {");
lines.push("  const t = new Date().toISOString().substring(11, 19);");
lines.push("  console.log('[' + t + '] ' + msg);");
lines.push("}");
lines.push("");
lines.push("function sleep(ms) { return new Promise(r => setTimeout(r, ms)); }");
lines.push("");
lines.push("function saveBase64(b64, filepath) {");
lines.push("  fs2.writeFileSync(filepath, Buffer.from(b64, 'base64'));");
lines.push("}");
lines.push("");
lines.push("function downloadUrl(url, filepath) {");
lines.push("  return new Promise((resolve, reject) => {");
lines.push("    const file = fs2.createWriteStream(filepath);");
lines.push("    https.get(url, res => {");
lines.push("      res.pipe(file);");
lines.push("      file.on('finish', () => { file.close(); resolve(); });");
lines.push("    }).on('error', err => { fs2.unlink(filepath, () => {}); reject(err); });");
lines.push("  });");
lines.push("}");
lines.push("");
lines.push("function generateImageOpenAI(prompt, quality) {");
lines.push("  return new Promise((resolve, reject) => {");
lines.push("    if (!OPENAI_KEY) { reject(new Error('OPENAI_API_KEY not set')); return; }");
lines.push("    const body = JSON.stringify({");
lines.push("      model: 'gpt-image-1', prompt, n: 1, size: SIZE, quality: quality || 'high',");
lines.push("    });");
lines.push("    const options = {");
lines.push("      hostname: 'api.openai.com', path: '/v1/images/generations', method: 'POST',");
lines.push("      headers: { 'Content-Type': 'application/json', 'Authorization': 'Bearer ' + OPENAI_KEY, 'Content-Length': Buffer.byteLength(body) },");
lines.push("    };");
lines.push("    const req = https.request(options, res => {");
lines.push("      let data = '';");
lines.push("      res.on('data', c => data += c);");
lines.push("      res.on('end', () => {");
lines.push("        try {");
lines.push("          const json = JSON.parse(data);");
lines.push("          if (json.error) { reject(new Error(json.error.message)); return; }");
lines.push("          const item = json.data[0];");
lines.push("          if (item.b64_json) resolve({ type: 'b64', value: item.b64_json });");
lines.push("          else if (item.url) resolve({ type: 'url', value: item.url });");
lines.push("          else reject(new Error('No image data in response'));");
lines.push("        } catch (e) {");
lines.push("          reject(new Error('Parse error: ' + e.message));");
lines.push("        }");
lines.push("      });");
lines.push("    });");
lines.push("    req.on('error', reject);");
lines.push("    req.write(body);");
lines.push("    req.end();");
lines.push("  });");
lines.push("}");
lines.push("");
lines.push("async function generateImageFal(prompt, imageStyle) {");
lines.push("  const falKey = process.env.FAL_KEY;");
lines.push("  if (!falKey) throw new Error('FAL_KEY not set');");
lines.push("  process.chdir('/data/pipeline');");
lines.push("  const { fal } = require('@fal-ai/client');");
lines.push("  fal.config({ credentials: falKey });");
lines.push("  const model = 'fal-ai/flux/dev';");
lines.push("  const result = await fal.subscribe(model, {");
lines.push("    input: {");
lines.push("      prompt: prompt,");
lines.push("      image_size: { width: 1536, height: 1024 },");
lines.push("      num_images: 1,");
lines.push("      enable_safety_checker: false,");
lines.push("    },");
lines.push("  });");
lines.push("  const url = result.data.images[0].url;");
lines.push("  return { type: 'url', value: url };");
lines.push("}");
lines.push("");
lines.push("function makeOpenAIProvider(quality) {");
lines.push("  return {");
lines.push("    generate: async ({ prompt, outputPath }) => {");
lines.push("      const startedAt = Date.now();");
lines.push("      try {");
lines.push("        const result = await generateImageOpenAI(prompt, quality);");
lines.push("        if (result.type === 'b64') saveBase64(result.value, outputPath);");
lines.push("        else await downloadUrl(result.value, outputPath);");
lines.push("        return { success: true, path: outputPath, provider: 'openai_images', durationMs: Date.now() - startedAt };");
lines.push("      } catch (err) {");
lines.push("        return { success: false, statusCode: 0, error: err.message };");
lines.push("      }");
lines.push("    },");
lines.push("  };");
lines.push("}");
lines.push("");
lines.push("function makeFluxProvider(imageStyle) {");
lines.push("  return {");
lines.push("    generate: async ({ prompt, outputPath }) => {");
lines.push("      const startedAt = Date.now();");
lines.push("      try {");
lines.push("        const result = await generateImageFal(prompt, imageStyle);");
lines.push("        await downloadUrl(result.value, outputPath);");
lines.push("        return { success: true, path: outputPath, provider: 'flux', durationMs: Date.now() - startedAt };");
lines.push("      } catch (err) {");
lines.push("        return { success: false, statusCode: 0, error: err.message };");
lines.push("      }");
lines.push("    },");
lines.push("  };");
lines.push("}");
lines.push("");
lines.push("function estimateImageCost(provider) {");
lines.push("  if (provider === 'openai_images') return 0.08;");
lines.push("  if (provider === 'flux')          return 0.025;");
lines.push("  if (provider === 'sdxl')          return 0.0043;");
lines.push("  return null;");
lines.push("}");
lines.push("");
lines.push("async function generateImages({ promptsFile, outputDir, channel, episodeId }) {");
lines.push("  if (!fs2.existsSync(promptsFile)) throw new Error('[image-gen] prompts file not found: ' + promptsFile);");
lines.push("");
lines.push("  const prompts = JSON.parse(fs2.readFileSync(promptsFile, 'utf8'));");
lines.push("  fs2.mkdirSync(outputDir, { recursive: true });");
lines.push("");
lines.push("  let imagePrimary   = 'openai_images';");
lines.push("  let imageSecondary = 'flux';");
lines.push("  let imageTertiary  = null;");
lines.push("  let imageStyle = 'dark-moody';");
lines.push("  let quality = 'high';");
lines.push("");
lines.push("  if (channel) {");
lines.push("    try {");
lines.push("      const dna = await getChannelConfigByLabel(channel);");
lines.push("      imagePrimary   = dna.image_primary   || 'openai_images';");
lines.push("      imageSecondary = dna.image_secondary || 'flux';");
lines.push("      imageTertiary  = dna.image_tertiary  || null;");
lines.push("      imageStyle = dna.image_style   || 'dark-moody';");
lines.push("      quality    = (dna.image_style && dna.image_style.includes('infographic')) ? 'medium' : 'high';");
lines.push("      log('[image-gen] Channel: ' + channel + ' | providers: ' + [imagePrimary, imageSecondary, imageTertiary].filter(Boolean).join(' -> ') + ' | style: ' + imageStyle);");
lines.push("    } catch (e) {");
lines.push("      log('[image-gen] WARNING: could not load channel DNA: ' + e.message + ' — using defaults');");
lines.push("    }");
lines.push("  }");
lines.push("");
lines.push("  const priorityList = [imagePrimary, imageSecondary, imageTertiary].filter(Boolean);");
lines.push("");
lines.push("  const providers = {");
lines.push("    openai_images: makeOpenAIProvider(quality),");
lines.push("    flux: makeFluxProvider(imageStyle),");
lines.push("    sdxl,");
lines.push("  };");
lines.push("");
lines.push("  const imageRouter = createRouter({ step: 'image', providers, estimateCost: estimateImageCost });");
lines.push("");
lines.push("  log('');");
lines.push("  log('════════════════════════════════════════');");
lines.push("  log('GENERATING ' + prompts.length + ' IMAGES via ' + priorityList.join(' -> '));");
lines.push("  log('Output: ' + outputDir);");
lines.push("  log('════════════════════════════════════════');");
lines.push("  log('');");
lines.push("");
lines.push("  let success = 0, skipped = 0, failed = 0;");
lines.push("");
lines.push("  for (let i = 0; i < prompts.length; i++) {");
lines.push("    const item    = prompts[i];");
lines.push("    const outPath = path.join(outputDir, item.filename);");
lines.push("");
lines.push("    if (fs2.existsSync(outPath)) {");
lines.push("      log('SKIP ' + item.shotId + ' — already exists');");
lines.push("      skipped++; continue;");
lines.push("    }");
lines.push("");
lines.push("    log('[' + (i + 1) + '/' + prompts.length + '] ' + item.shotId);");
lines.push("");
lines.push("    try {");
lines.push("      const result = await imageRouter.run(priorityList, {");
lines.push("        input: { prompt: item.prompt, negativePrompt: '', width: 1536, height: 1024, outputPath: outPath },");
lines.push("        providerConfig: {},");
lines.push("        episodeId: episodeId || null,");
lines.push("        shotId: item.shotId,");
lines.push("        costUnits: null,");
lines.push("      });");
lines.push("");
lines.push("      log('  OK: ' + item.filename + ' (via ' + result.provider + ')');");
lines.push("      success++;");
lines.push("      if (i < prompts.length - 1) await sleep(SLEEP_MS);");
lines.push("    } catch (err) {");
lines.push("      log('  FAILED ' + item.shotId + ': ' + err.message);");
lines.push("      failed++;");
lines.push("      await sleep(SLEEP_FAIL);");
lines.push("    }");
lines.push("  }");
lines.push("");
lines.push("  log('');");
lines.push("  log('════════════════════════════════════════');");
lines.push("  log('COMPLETE — ' + success + ' generated | ' + skipped + ' skipped | ' + failed + ' failed');");
lines.push("  log('════════════════════════════════════════');");
lines.push("  return { success, skipped, failed };");
lines.push("}");
lines.push("");
lines.push("if (require.main === module) {");
lines.push("  const args = process.argv.slice(2);");
lines.push("  let episode = null, promptsFile = null, outputDir = null, channel = null;");
lines.push("  for (let i = 0; i < args.length; i++) {");
lines.push("    if (args[i] === '--episode')      episode     = args[++i];");
lines.push("    if (args[i] === '--prompts-file') promptsFile = args[++i];");
lines.push("    if (args[i] === '--output-dir')   outputDir   = args[++i];");
lines.push("    if (args[i] === '--channel')      channel     = args[++i];");
lines.push("  }");
lines.push("  if (episode && !promptsFile) {");
lines.push("    const episodeDir = path.join('/data/pipeline/episodes', episode);");
lines.push("    promptsFile = path.join(episodeDir, 'assets', 'stills', 'pending-prompts.json');");
lines.push("    outputDir   = path.join(episodeDir, 'assets', 'stills');");
lines.push("  }");
lines.push("  if (!promptsFile || !outputDir) {");
lines.push("    console.error('Usage: node surface-image-generator.cjs --episode EP4 --channel \"Empire Omitted\"');");
lines.push("    process.exit(1);");
lines.push("  }");
lines.push("  generateImages({ promptsFile, outputDir, channel })");
lines.push("    .catch(err => { console.error('[image-gen] FATAL:', err.message); process.exit(1); });");
lines.push("}");
lines.push("");
lines.push("module.exports = { generateImages };");
lines.push("");

const content = lines.join('\n');
fs.writeFileSync(p, content, 'utf8');
console.log('[image-gen writer] written — lines: ' + content.split('\n').length);
