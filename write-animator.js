const fs = require('fs');
const p = '/data/pipeline/surface-animator.cjs';

const lines = [];
lines.push("'use strict';");
lines.push("");
lines.push("require('dotenv').config();");
lines.push("");
lines.push("const fs2   = require('fs');");
lines.push("const path  = require('path');");
lines.push("const https = require('https');");
lines.push("const http  = require('http');");
lines.push("const { getChannelConfigByLabel } = require('./config-reader.cjs');");
lines.push("const { createRouter } = require('./providers/provider-router.cjs');");
lines.push("const svd = require('./providers/video/svd.cjs');");
lines.push("");
lines.push("const KLING_MODEL   = 'fal-ai/kling-video/v1.6/standard/image-to-video';");
lines.push("const CLIP_DURATION = '5';");
lines.push("const ASPECT_RATIO  = '16:9';");
lines.push("const SLEEP_BETWEEN = 3000;");
lines.push("const SLEEP_FAIL    = 8000;");
lines.push("");
lines.push("const ANIMATION_DEFAULTS = {");
lines.push("  'minimal':  'Slow cinematic push in, subtle camera movement, documentary atmosphere, dark moody lighting, shallow depth of field',");
lines.push("  'dramatic': 'Dynamic camera movement, fast zoom, high contrast lighting, intense atmosphere, cinematic thriller style',");
lines.push("  'none':     '',");
lines.push("  'subtle-ken-burns': 'Very slow pan across the image, archival documentary style, gentle zoom, warm lighting',");
lines.push("};");
lines.push("");
lines.push("function log(msg) { console.log(msg); }");
lines.push("function sleep(ms) { return new Promise(r => setTimeout(r, ms)); }");
lines.push("");
lines.push("function downloadFile(url, dest) {");
lines.push("  return new Promise((resolve, reject) => {");
lines.push("    const file = fs2.createWriteStream(dest);");
lines.push("    const protocol = url.startsWith('https') ? https : http;");
lines.push("    protocol.get(url, response => {");
lines.push("      response.pipe(file);");
lines.push("      file.on('finish', () => { file.close(); resolve(); });");
lines.push("    }).on('error', err => { fs2.unlink(dest, () => {}); reject(err); });");
lines.push("  });");
lines.push("}");
lines.push("");
lines.push("function makeKlingProvider(animPromptFor) {");
lines.push("  return {");
lines.push("    generate: async ({ sourceImagePath, outputPath, shotId }) => {");
lines.push("      const startedAt = Date.now();");
lines.push("      try {");
lines.push("        const falKey = process.env.FAL_KEY;");
lines.push("        if (!falKey) return { success: false, statusCode: 401, error: '[animator] FAL_KEY not set' };");
lines.push("");
lines.push("        process.chdir('/data/pipeline');");
lines.push("        const { fal } = require('@fal-ai/client');");
lines.push("        fal.config({ credentials: falKey });");
lines.push("");
lines.push("        const imageBuffer = fs2.readFileSync(sourceImagePath);");
lines.push("        const imageBlob   = new Blob([imageBuffer], { type: 'image/png' });");
lines.push("        const uploadedUrl = await fal.storage.upload(imageBlob);");
lines.push("        log('    Uploaded to fal.ai storage');");
lines.push("");
lines.push("        const result = await fal.subscribe(KLING_MODEL, {");
lines.push("          input: {");
lines.push("            image_url:    uploadedUrl,");
lines.push("            prompt:       animPromptFor(shotId),");
lines.push("            duration:     CLIP_DURATION,");
lines.push("            aspect_ratio: ASPECT_RATIO,");
lines.push("          },");
lines.push("          logs: false,");
lines.push("          onQueueUpdate: (update) => {");
lines.push("            if (update.status === 'IN_PROGRESS') process.stdout.write('.');");
lines.push("          },");
lines.push("        });");
lines.push("        process.stdout.write('\\n');");
lines.push("");
lines.push("        const videoUrl = result.data.video.url;");
lines.push("        await downloadFile(videoUrl, outputPath);");
lines.push("        return { success: true, path: outputPath, provider: 'kling', durationMs: Date.now() - startedAt };");
lines.push("      } catch (err) {");
lines.push("        return { success: false, statusCode: 0, error: err.message };");
lines.push("      }");
lines.push("    },");
lines.push("  };");
lines.push("}");
lines.push("");
lines.push("function estimateVideoCost(provider) {");
lines.push("  if (provider === 'kling') return 0.35;");
lines.push("  if (provider === 'svd')   return 0.18;");
lines.push("  return null;");
lines.push("}");
lines.push("");
lines.push("async function animateClips({ shotDefs, episodeDir, channel, episodeId }) {");
lines.push("  let animationStyle = 'minimal';");
lines.push("  let imageMotion    = 'subtle-ken-burns';");
lines.push("  let videoPrimary   = 'kling';");
lines.push("  let videoSecondary = null;");
lines.push("  let videoTertiary  = null;");
lines.push("");
lines.push("  if (channel) {");
lines.push("    try {");
lines.push("      const dna = await getChannelConfigByLabel(channel);");
lines.push("      animationStyle = dna.animation_style || 'minimal';");
lines.push("      imageMotion    = dna.image_motion    || 'subtle-ken-burns';");
lines.push("      videoPrimary   = dna.video_primary   || 'kling';");
lines.push("      videoSecondary = dna.video_secondary || null;");
lines.push("      videoTertiary  = dna.video_tertiary  || null;");
lines.push("      log('[animator] Channel: ' + channel + ' | animation_style: ' + animationStyle + ' | image_motion: ' + imageMotion);");
lines.push("    } catch (e) {");
lines.push("      log('[animator] WARNING: could not load channel DNA: ' + e.message);");
lines.push("    }");
lines.push("  }");
lines.push("");
lines.push("  if (animationStyle === 'none' || imageMotion === 'still') {");
lines.push("    log('[animator] Channel DNA says no animation — skipping animator entirely');");
lines.push("    return { completed: 0, skipped: 0, failed: 0 };");
lines.push("  }");
lines.push("");
lines.push("  if (animationStyle === 'motion-graphics-only') {");
lines.push("    log('[animator] Channel DNA says motion-graphics-only — skipping fal.ai Kling cinematic clip animation.');");
lines.push("    log('[animator] NOTE: this does NOT produce animated charts / counting numbers.');");
lines.push("    log('[animator] No module in this pipeline currently renders that — it needs new build work,');");
lines.push("    log('[animator] not just this config value. See build report for details.');");
lines.push("    return { completed: 0, skipped: 0, failed: 0, motionGraphicsPending: true };");
lines.push("  }");
lines.push("");
lines.push("  const stillsDir = path.join(episodeDir, 'assets', 'stills');");
lines.push("  const clipsDir  = path.join(episodeDir, 'assets', 'clips');");
lines.push("  fs2.mkdirSync(clipsDir, { recursive: true });");
lines.push("");
lines.push("  const defaultPrompt = ANIMATION_DEFAULTS[animationStyle] || ANIMATION_DEFAULTS['minimal'];");
lines.push("");
lines.push("  const clipShots = (shotDefs.allShots || []).filter(s => s.visualType === 'CLIP');");
lines.push("");
lines.push("  if (clipShots.length === 0) {");
lines.push("    log('[animator] No CLIP shots found — nothing to animate');");
lines.push("    return { completed: 0, skipped: 0, failed: 0 };");
lines.push("  }");
lines.push("");
lines.push("  const shotPromptById = {};");
lines.push("  for (const shot of clipShots) shotPromptById[shot.shotId] = shot.animationPrompt || defaultPrompt;");
lines.push("");
lines.push("  const providers = {");
lines.push("    kling: makeKlingProvider((shotId) => shotPromptById[shotId]),");
lines.push("    svd,");
lines.push("  };");
lines.push("  const priorityList = [videoPrimary, videoSecondary, videoTertiary].filter(Boolean);");
lines.push("  const videoRouter = createRouter({ step: 'video', providers, estimateCost: estimateVideoCost });");
lines.push("");
lines.push("  log('');");
lines.push("  log('[animator] ════════════════════════════════════════');");
lines.push("  log('[animator] ANIMATING ' + clipShots.length + ' CLIPS via ' + priorityList.join(' -> '));");
lines.push("  log('[animator] Style: ' + animationStyle);");
lines.push("  log('[animator] ════════════════════════════════════════');");
lines.push("  log('');");
lines.push("");
lines.push("  let completed = 0, skipped = 0, failed = 0;");
lines.push("");
lines.push("  for (let i = 0; i < clipShots.length; i++) {");
lines.push("    const shot        = clipShots[i];");
lines.push("    const clipFile    = path.join(clipsDir, shot.shotId + '.mp4');");
lines.push("    const sourceImage = path.join(stillsDir, shot.shotId + '.png');");
lines.push("");
lines.push("    if (fs2.existsSync(clipFile)) {");
lines.push("      log('  SKIP [' + shot.shotId + '] — clip already exists');");
lines.push("      skipped++; continue;");
lines.push("    }");
lines.push("    if (!fs2.existsSync(sourceImage)) {");
lines.push("      log('  SKIP [' + shot.shotId + '] — source image not found');");
lines.push("      skipped++; continue;");
lines.push("    }");
lines.push("");
lines.push("    log('  [' + (i + 1) + '/' + clipShots.length + '] Animating ' + shot.shotId + '...');");
lines.push("");
lines.push("    try {");
lines.push("      const result = await videoRouter.run(priorityList, {");
lines.push("        input: { sourceImagePath: sourceImage, animationStyle, outputPath: clipFile, shotId: shot.shotId },");
lines.push("        providerConfig: {},");
lines.push("        episodeId: episodeId || null,");
lines.push("        shotId: shot.shotId,");
lines.push("        costUnits: null,");
lines.push("      });");
lines.push("      completed++;");
lines.push("      log('    OK: ' + path.basename(clipFile) + ' (' + completed + '/' + clipShots.length + ', via ' + result.provider + ')');");
lines.push("      if (i < clipShots.length - 1) await sleep(SLEEP_BETWEEN);");
lines.push("    } catch (err) {");
lines.push("      failed++;");
lines.push("      log('    FAILED [' + shot.shotId + ']: ' + err.message);");
lines.push("      await sleep(SLEEP_FAIL);");
lines.push("    }");
lines.push("  }");
lines.push("");
lines.push("  log('');");
lines.push("  log('[animator] COMPLETE — ' + completed + ' animated | ' + skipped + ' skipped | ' + failed + ' failed');");
lines.push("  return { completed, skipped, failed };");
lines.push("}");
lines.push("");
lines.push("if (require.main === module) {");
lines.push("  const args = process.argv.slice(2);");
lines.push("  let episode = null, channel = null;");
lines.push("  for (let i = 0; i < args.length; i++) {");
lines.push("    if (args[i] === '--episode') episode = args[++i];");
lines.push("    if (args[i] === '--channel') channel = args[++i];");
lines.push("  }");
lines.push("  if (!episode) {");
lines.push("    console.error('Usage: node surface-animator.cjs --episode EP4 --channel \"Empire Omitted\"');");
lines.push("    process.exit(1);");
lines.push("  }");
lines.push("  const episodeDir   = path.join('/data/pipeline/episodes', episode);");
lines.push("  const shotDefsPath = path.join(episodeDir, 'shot-definitions.json');");
lines.push("  if (!fs2.existsSync(shotDefsPath)) {");
lines.push("    console.error('[animator] shot-definitions.json not found at ' + shotDefsPath);");
lines.push("    process.exit(1);");
lines.push("  }");
lines.push("  const shotDefs = JSON.parse(fs2.readFileSync(shotDefsPath, 'utf8'));");
lines.push("  animateClips({ shotDefs, episodeDir, channel })");
lines.push("    .catch(err => { console.error('[animator] FATAL:', err.message); process.exit(1); });");
lines.push("}");
lines.push("");
lines.push("module.exports = { animateClips };");
lines.push("");

const content = lines.join('\n');
fs.writeFileSync(p, content, 'utf8');
console.log('[animator writer] written — lines: ' + content.split('\n').length);
