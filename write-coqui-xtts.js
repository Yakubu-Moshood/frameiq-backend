lines.push("      await sleep(POLL_INTERVAL_MS);");
lines.push("      const poll = await replicateRequest('GET', `/v1/predictions/${predictionId}`);");
lines.push("      if (poll.statusCode >= 400) {");
lines.push("        return { success: false, statusCode: poll.statusCode, error: `Poll failed: HTTP ${poll.statusCode}` };");
lines.push("      }");
lines.push("      prediction = poll.body;");
lines.push("    }");
lines.push("");
lines.push("    if (prediction.status !== 'succeeded') {");
