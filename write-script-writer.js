const fs = require('fs');
const p = '/data/pipeline/surface-script-writer.cjs';

const lines = [];
lines.push("'use strict';");
lines.push('');
lines.push("require('dotenv').config();");
lines.push('');
lines.push("const fs2 = require('fs');");
lines.push("const path = require('path');");
lines.push("const Anthropic = require('@anthropic-ai/sdk');");
lines.push("const { getChannelConfigByLabel } = require('./config-reader.cjs');");
lines.push('');
lines.push("const MODEL      = 'claude-opus-4-5';");
lines.push('const MAX_TOKENS = 16000;');
lines.push('');
lines.push('function buildScriptConfig(dna) {');
lines.push('  const mins = dna.target_length_minutes || 10;');
lines.push('  const wordsPerMin = 120;');
lines.push('  const totalWords = Math.round(mins * wordsPerMin);');
lines.push("  const channelLabel = dna.label || 'FraymIQ';");
lines.push('');
lines.push('  const styleMap = {');
lines.push("    'dramatic-investigative': [");
lines.push("      'Tone: Authoritative, dramatic, measured. Like a serious BBC/Netflix documentary narrator.',");
lines.push("      'Sentence rhythm: Short punches. Long builds. Then a short punch again.',");
lines.push("      'Use ellipsis (...) for dramatic pauses within sentences.',");
lines.push("      'Each act ends on a cliffhanger or pivot that pulls the viewer forward.',");
lines.push("      'No filler phrases. No first-person narrator opinion. Let the facts do the work.',");
lines.push("      'Numbers always written with commas and currency symbols.',");
lines.push("      'Avoid passive voice where possible. Make it visceral.',");
lines.push('    ],');
lines.push("    'calm-explainer': [");
lines.push("      'Tone: Friendly, clear, authoritative. Like a trusted finance teacher explaining to a smart friend.',");
lines.push("      'Sentence rhythm: Short and clear. No jargon without explanation.',");
lines.push("      'No ellipsis. No cliffhangers. Just clarity and insight.',");
lines.push("      'Each section builds logically on the last.',");
lines.push("      'Use relatable analogies to explain abstract concepts.',");
lines.push("      'Conversational but precise. Never condescending.',");
lines.push('    ],');
lines.push("    'suspenseful': [");
lines.push("      'Tone: Dark, tense, gripping. Like a true crime podcast at its most intense.',");
lines.push("      'Sentence rhythm: Short. Abrupt. Then silence. Then the reveal.',");
lines.push("      'Use pauses and rhetorical questions to build dread.',");
lines.push("      'Each act ends on a disturbing revelation or unanswered question.',");
lines.push("      'Names, dates, locations — be specific. Specificity creates horror.',");
lines.push("      'Never let the listener feel safe.',");
lines.push('    ],');
lines.push("    'reflective-historical': [");
lines.push("      'Tone: Measured, scholarly, reverent. Like a historian uncovering a forgotten truth.',");
lines.push("      'Sentence rhythm: Long builds with careful detail. Let history breathe.',");
lines.push("      'Use archival language where appropriate.',");
lines.push("      'Each act reveals a layer of history that recontextualises what came before.',");
lines.push("      'Emphasise what was lost, hidden, or suppressed.',");
lines.push("      'End with the weight of what this history means today.',");
lines.push('    ],');
lines.push("    'sardonic': [");
lines.push("      'Tone: Dry, witty, incredulous. Like reading the best revenge story on Reddit out loud.',");
lines.push("      'Sentence rhythm: Build-up then punchline. Let the irony land.',");
lines.push("      'Use sarcasm sparingly but devastatingly.',");
lines.push("      'Each act escalates the absurdity of the situation.',");
lines.push("      'The narrator is clearly on the side of the person getting revenge.',");
lines.push("      'End with satisfaction. Justice served.',");
lines.push('    ],');
lines.push('  };');
lines.push('');
lines.push("  const style = styleMap[dna.narration_style] || styleMap['dramatic-investigative'];");
lines.push("  const styleText = style.map(s => '- ' + s).join('\\n');");
lines.push('');
lines.push('  const act1Min  = Math.round(totalWords * 0.17);');
lines.push('  const act2Min  = Math.round(totalWords * 0.20);');
lines.push('  const act3Min  = Math.round(totalWords * 0.20);');
lines.push('  const act3bMin = Math.round(totalWords * 0.12);');
lines.push('  const act4Min  = Math.round(totalWords * 0.20);');
lines.push('  const act5Min  = Math.round(totalWords * 0.11);');
lines.push('');
lines.push("  const pacing = dna.script_pacing || 'slow-build';");
lines.push('  const pacingNote = pacing === \'fast-cut\'');
lines.push("    ? 'PACING: Fast. Cut quickly between revelations. Keep momentum high throughout.'");
lines.push('    : pacing === \'steady\'');
lines.push("    ? 'PACING: Steady and measured. Each section flows naturally into the next.'");
lines.push("    : 'PACING: Slow build. Each act increases tension toward a climax.';");
lines.push('');
lines.push('  return {');
lines.push('    styleText, totalWords, mins,');
lines.push('    act1Min, act2Min, act3Min, act3bMin, act4Min, act5Min,');
lines.push('    pacingNote, channelLabel,');
lines.push("    outroLine: 'Subscribe to ' + channelLabel + ' — new episodes every week.',");
lines.push('  };');
lines.push('}');
lines.push('');
lines.push("async function writeScript({ topic, channel = 'Empire Omitted', outputDir = null }) {");
lines.push("  if (!topic) throw new Error('surface-script-writer: topic is required');");
lines.push('');
lines.push('  const dna = await getChannelConfigByLabel(channel);');
lines.push('  const cfg = buildScriptConfig(dna);');
lines.push('  const client = new Anthropic();');
lines.push('');
lines.push("  console.log('[script-writer] Channel: ' + channel);");
lines.push("  console.log('[script-writer] Blueprint: ' + dna.blueprint_label);");
lines.push("  console.log('[script-writer] Target length: ' + cfg.mins + ' min / ' + cfg.totalWords + ' words');");
lines.push("  console.log('[script-writer] Writing script for: \"' + topic + '\"');");
lines.push('');
lines.push("  const systemPrompt = 'You are an expert scriptwriter for ' + cfg.channelLabel + ', a ' + dna.blueprint_label + ' YouTube channel.\\n\\n' +");
lines.push("    'CHANNEL STYLE:\\n' + cfg.styleText + '\\n\\n' +");
lines.push("    cfg.pacingNote + '\\n\\n' +");
lines.push("    'You will return a complete 5-act script as a JSON object.\\n\\n' +");
lines.push("    'RESPONSE FORMAT — return ONLY valid JSON, no markdown fences, no preamble:\\n' +");
lines.push("    '{\\n' +");
lines.push("    '  \"title\": \"Full YouTube title including | ' + cfg.channelLabel + '\",\\n' +");
lines.push("    '  \"topic\": \"The topic as given\",\\n' +");
lines.push("    '  \"totalEstimatedSeconds\": <number>,\\n' +");
lines.push("    '  \"acts\": {\\n' +");
lines.push("    '    \"act1\": { \"label\": \"THE HOOK\", \"estimatedSeconds\": <number>, \"voScript\": \"<narration>\" },\\n' +");
lines.push("    '    \"act2\": { \"label\": \"THE RISE\", \"estimatedSeconds\": <number>, \"voScript\": \"<narration>\" },\\n' +");
lines.push("    '    \"act3\": { \"label\": \"THE TRUTH\", \"estimatedSeconds\": <number>, \"voScript\": \"<narration>\" },\\n' +");
lines.push("    '    \"act3b\": { \"label\": \"THE COST\", \"estimatedSeconds\": <number>, \"voScript\": \"<narration>\" },\\n' +");
lines.push("    '    \"act4\": { \"label\": \"THE FALL\", \"estimatedSeconds\": <number>, \"voScript\": \"<narration>\" },\\n' +");
lines.push("    '    \"act5\": { \"label\": \"THE VERDICT\", \"estimatedSeconds\": <number>, \"voScript\": \"<narration>\" }\\n' +");
lines.push("    '  },\\n' +");
lines.push("    '  \"youtubeDetails\": {\\n' +");
lines.push("    '    \"description\": \"<2-3 paragraph description>\",\\n' +");
lines.push("    '    \"tags\": [\"tag1\", \"tag2\"],\\n' +");
lines.push("    '    \"chapters\": [{ \"time\": \"0:00\", \"label\": \"Intro\" }]\\n' +");
lines.push("    '  }\\n' +");
lines.push("    '}\\n\\n' +");
lines.push("    'WORD COUNT — MANDATORY:\\n' +");
lines.push("    'act1: minimum ' + cfg.act1Min + ' words\\n' +");
lines.push("    'act2: minimum ' + cfg.act2Min + ' words\\n' +");
lines.push("    'act3: minimum ' + cfg.act3Min + ' words\\n' +");
lines.push("    'act3b: minimum ' + cfg.act3bMin + ' words\\n' +");
lines.push("    'act4: minimum ' + cfg.act4Min + ' words\\n' +");
lines.push("    'act5: minimum ' + cfg.act5Min + ' words\\n' +");
lines.push("    'TOTAL minimum: ' + cfg.totalWords + ' words. Target runtime: ' + cfg.mins + ' minutes.\\n' +");
lines.push("    'End act5 with: \"' + cfg.outroLine + '\"';");
lines.push('');
lines.push("  const userPrompt = 'Write a complete 5-act script about:\\n\\n' + topic + '\\n\\nReturn only the JSON object. No markdown. No preamble.';");
lines.push('');
lines.push('  const message = await client.messages.create({');
lines.push('    model:      MODEL,');
lines.push('    max_tokens: MAX_TOKENS,');
lines.push('    system:     systemPrompt,');
lines.push("    messages:   [{ role: 'user', content: userPrompt }],");
lines.push('  });');
lines.push('');
lines.push("  const rawText = message.content.filter(b => b.type === 'text').map(b => b.text).join('');");
lines.push('  const clean = rawText.replace(/^```json\\s*/i, \'\').replace(/\\s*```$/, \'\').trim();');
lines.push('');
lines.push('  let script;');
lines.push('  try {');
lines.push('    script = JSON.parse(clean);');
lines.push('  } catch (err) {');
lines.push("    throw new Error('[script-writer] JSON parse failed: ' + err.message);");
lines.push('  }');
lines.push('');
lines.push("  const requiredActs = ['act1', 'act2', 'act3', 'act3b', 'act4', 'act5'];");
lines.push('  for (const act of requiredActs) {');
lines.push("    if (!script.acts?.[act]?.voScript) throw new Error('[script-writer] Missing voScript for ' + act);");
lines.push('  }');
lines.push('');
lines.push("  console.log('[script-writer] Script complete — ' + script.totalEstimatedSeconds + 's estimated');");
lines.push("  console.log('[script-writer] Title: ' + script.title);");
lines.push('');
lines.push('  if (outputDir) {');
lines.push('    fs2.mkdirSync(outputDir, { recursive: true });');
lines.push("    const jsonPath = path.join(outputDir, 'script.json');");
lines.push("    const txtPath  = path.join(outputDir, 'script-plain.txt');");
lines.push("    fs2.writeFileSync(jsonPath, JSON.stringify(script, null, 2), 'utf8');");
lines.push("    fs2.writeFileSync(txtPath, buildPlainText(script), 'utf8');");
lines.push("    console.log('[script-writer] Saved to ' + outputDir);");
lines.push('  }');
lines.push('');
lines.push('  return script;');
lines.push('}');
lines.push('');
lines.push('function buildPlainText(script) {');
lines.push("  const lines2 = [script.title, '='.repeat(60), ''];");
lines.push('  for (const [key, act] of Object.entries(script.acts)) {');
lines.push("    lines2.push('--- ' + key.toUpperCase() + ' — ' + act.label + ' (~' + act.estimatedSeconds + 's) ---');");
lines.push("    lines2.push('');");
lines.push('    lines2.push(act.voScript);');
lines.push("    lines2.push('');");
lines.push('  }');
lines.push("  lines2.push('--- YOUTUBE DETAILS ---');");
lines.push("  lines2.push('');");
lines.push("  lines2.push('DESCRIPTION:');");
lines.push('  lines2.push(script.youtubeDetails.description);');
lines.push("  lines2.push('');");
lines.push("  lines2.push('TAGS: ' + script.youtubeDetails.tags.join(', '));");
lines.push("  return lines2.join('\\n');");
lines.push('}');
lines.push('');
lines.push('if (require.main === module) {');
lines.push('  const topic     = process.argv[2];');
lines.push("  const channel   = process.argv[3] || 'Empire Omitted';");
lines.push('  const outputDir = process.argv[4] || null;');
lines.push('  if (!topic) {');
lines.push("    console.error('Usage: node surface-script-writer.cjs \"<topic>\" \"<channel>\" [outputDir]');");
lines.push('    process.exit(1);');
lines.push('  }');
lines.push('  writeScript({ topic, channel, outputDir })');
lines.push('    .then(script => { if (!outputDir) console.log(buildPlainText(script)); })');
lines.push("    .catch(err => { console.error('[script-writer] FATAL:', err.message); process.exit(1); });");
lines.push('}');
lines.push('');
lines.push('module.exports = { writeScript };');

const content = lines.join('\n');
fs.writeFileSync(p, content, 'utf8');
console.log('surface-script-writer.cjs written — lines: ' + content.split('\n').length);
