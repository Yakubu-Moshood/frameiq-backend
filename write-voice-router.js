const fs = require('fs');
const p = '/data/pipeline/providers/voice-router.cjs';

const lines = [];
lines.push("'use strict';");
lines.push("/**");
lines.push(" * providers/voice-router.cjs");
lines.push(" * Sprint 1.5 Phase B — Voice provider router");
lines.push(" *");
lines.push(" * Single export: generateVoice()");
lines.push(" * Called by voiceover-generator.cjs instead of calling ElevenLabs directly.");
lines.push(" *");
lines.push(" * Responsibilities:");
lines.push(" *   - Read provider priority from channelConfig (set in Phase A)");
lines.push(" *   - Provider locking: one provider per episode (set on first act, reused for all)");
lines.push(" *   - Failover: ElevenLabs → OpenAI TTS → Coqui XTTS-v2 (third tier, added below)");
lines.push(" *   - Circuit breaker: 3 failures in 10 min → skip provider for 15 min");
lines.push(" *   - Retry logic: per-failure-type retry before failover");
lines.push(" *   - provider_events logging: one row per attempt per act");
lines.push(" *   - Episode field updates: voice_provider_used, provider_substituted");
lines.push(" *");
lines.push(" * Third-tier addition (open-source fallback investigation):");
lines.push(" *   - voice_tertiary (channel_dna, see migrations/012_voice_tertiary.js) is");
lines.push(" *     now included in the priority list, same as voice_primary/voice_secondary.");
lines.push(" *   - coqui_xtts registered in PROVIDERS, backed by providers/voice/coqui-xtts.cjs");
lines.push(" *     (Coqui XTTS-v2 via Replicate -- reference-audio voice cloning, not a");
lines.push(" *     simple voice-ID string; see that file's own header comment).");
lines.push(" *   - estimateCost() extended with Replicate's real per-run pricing for");
lines.push(" *     lucataco/xtts-v2 (~$0.069/run, confirmed live at investigation time).");
lines.push(" *   - Everything else in this file (circuit breaker, retry, locking, event");
lines.push(" *     logging) is completely unchanged -- the whole point was to slot the");
lines.push(" *     third tier into the existing generic mechanism, not rebuild it.");
lines.push(" */");
lines.push("const path = require('path');");
lines.push("const { v4: uuid } = require('uuid');");
lines.push("// Provider implementations");
lines.push("const elevenlabs = require('./voice/elevenlabs.cjs');");
lines.push("const openaiTts  = require('./voice/openai-tts.cjs');");
lines.push("const coquiXtts  = require('./voice/coqui-xtts.cjs');");
lines.push("// DB helpers — absolute path for Railway Volume compatibility");
lines.push("const DB_MODULE_PATH = process.env.DB_MODULE_PATH || '/app/db';");
lines.push("const { run, get }   = require(DB_MODULE_PATH);");
lines.push("// ── Provider registry ─────────────────────────────────────────────────────────");
lines.push("const PROVIDERS = {");
lines.push("  elevenlabs: elevenlabs,");
lines.push("  openai_tts: openaiTts,");
lines.push("  coqui_xtts: coquiXtts,");
lines.push("};");
lines.push("// ── Circuit breaker state (in-memory, resets on deploy) ───────────────────────");
lines.push("const circuitBreaker = {");
lines.push("  // { [provider]: { failures: N, openUntil: timestamp|null } }");
lines.push("};");
lines.push("const CIRCUIT_OPEN_THRESHOLD = 3;");
lines.push("const CIRCUIT_OPEN_DURATION_MS = 15 * 60 * 1000; // 15 minutes");
lines.push("const CIRCUIT_WINDOW_MS = 10 * 60 * 1000;        // 10 minutes");
lines.push("function getCircuit(provider) {");
lines.push("  if (!circuitBreaker[provider]) {");
lines.push("    circuitBreaker[provider] = { failures: [], openUntil: null };");
lines.push("  }");
lines.push("  return circuitBreaker[provider];");
lines.push("}");
lines.push("function isCircuitOpen(provider) {");
lines.push("  const circuit = getCircuit(provider);");
lines.push("  if (circuit.openUntil && Date.now() < circuit.openUntil) {");
lines.push("    console.log(`[voice-router] Circuit OPEN for ${provider} — skipping until ${new Date(circuit.openUntil).toISOString()}`);");
lines.push("    return true;");
lines.push("  }");
lines.push("  if (circuit.openUntil && Date.now() >= circuit.openUntil) {");
lines.push("    circuit.openUntil = null;");
lines.push("    console.log(`[voice-router] Circuit HALF-OPEN for ${provider} — testing`);");
lines.push("  }");
lines.push("  return false;");
lines.push("}");
lines.push("function recordFailure(provider) {");
lines.push("  const circuit = getCircuit(provider);");
lines.push("  const now = Date.now();");
lines.push("  circuit.failures = circuit.failures.filter(t => now - t < CIRCUIT_WINDOW_MS);");
lines.push("  circuit.failures.push(now);");
lines.push("  if (circuit.failures.length >= CIRCUIT_OPEN_THRESHOLD) {");
lines.push("    circuit.openUntil = now + CIRCUIT_OPEN_DURATION_MS;");
lines.push("    console.log(`[voice-router] Circuit OPENED for ${provider} after ${circuit.failures.length} failures`);");
lines.push("  }");
lines.push("}");
lines.push("function recordSuccess(provider) {");
lines.push("  const circuit = getCircuit(provider);");
lines.push("  circuit.failures = [];");
lines.push("  circuit.openUntil = null;");
lines.push("}");
lines.push("// ── Provider locking (per episode) ────────────────────────────────────────────");
lines.push("const episodeLocks = {};");
lines.push("// ── Retry logic ───────────────────────────────────────────────────────────────");
lines.push("function shouldRetry(statusCode) {");
lines.push("  return statusCode === 429 || statusCode === 500 || statusCode === 503 || statusCode === 0;");
lines.push("}");
lines.push("function retryDelay(statusCode) {");
lines.push("  if (statusCode === 429) return 30000;");
lines.push("  if (statusCode === 500 || statusCode === 503) return 10000;");
lines.push("  return 5000;");
lines.push("}");
lines.push("function sleep(ms) {");
lines.push("  return new Promise(resolve => setTimeout(resolve, ms));");
lines.push("}");
lines.push("// ── DB logging helpers ────────────────────────────────────────────────────────");
lines.push("async function logProviderEvent({ episodeId, step, act, provider, tier, success, error, durationMs, costEstimate }) {");
lines.push("  try {");
lines.push("    await run(`");
lines.push("      INSERT INTO provider_events (id, episode_id, step, act, provider, tier, success, error_message, duration_ms, cost_estimate)");
lines.push("      VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?, ?)");
lines.push("    `, [");
lines.push("      uuid(), episodeId, step, act, provider, tier,");
lines.push("      success ? 1 : 0, error || null, durationMs || null, costEstimate || null,");
lines.push("    ]);");
lines.push("  } catch (err) {");
lines.push("    console.error('[voice-router] provider_events log failed:', err.message);");
lines.push("  }");
lines.push("}");
lines.push("async function updateEpisodeProviderFields({ episodeId, provider, substituted }) {");
lines.push("  try {");
lines.push("    await run(`");
lines.push("      UPDATE episodes");
lines.push("      SET voice_provider_used = ?, provider_substituted = ?");
lines.push("      WHERE id = ?");
lines.push("    `, [provider, substituted ? 1 : 0, episodeId]);");
lines.push("  } catch (err) {");
lines.push("    console.error('[voice-router] episode provider field update failed:', err.message);");
lines.push("  }");
lines.push("}");
lines.push("// ── Cost estimation ───────────────────────────────────────────────────────────");
lines.push("function estimateCost(provider, charCount) {");
lines.push("  if (provider === 'elevenlabs') {");
lines.push("    return Math.round((charCount / 100000) * 18 * 100) / 100;");
lines.push("  }");
lines.push("  if (provider === 'openai_tts') {");
lines.push("    return Math.round((charCount / 1000000) * 12 * 1000) / 1000;");
lines.push("  }");
lines.push("  if (provider === 'coqui_xtts') {");
lines.push("    // Replicate bills lucataco/xtts-v2 per run (Nvidia A100 80GB), not per");
lines.push("    // character -- confirmed live at investigation time: ~$0.069/run,");
lines.push("    // varies with input length. There's no per-character rate to scale by,");
lines.push("    // so this returns the flat per-run figure regardless of charCount.");
lines.push("    // Revisit if actual provider_events data shows this estimate drifting");
lines.push("    // from real Replicate billing once this tier is live.");
lines.push("    return 0.069;");
lines.push("  }");
lines.push("  return null;");
lines.push("}");
lines.push("// ── Main generateVoice function ───────────────────────────────────────────────");
lines.push("async function generateVoice({ text, act, channelConfig, episodeId, outputPath }) {");
lines.push("  const voicePrimary   = channelConfig.voice_primary   || 'elevenlabs';");
lines.push("  const voiceSecondary = channelConfig.voice_secondary || 'openai_tts';");
lines.push("  const voiceTertiary  = channelConfig.voice_tertiary  || null;");
lines.push("  const priorityList = [voicePrimary, voiceSecondary, voiceTertiary].filter(Boolean);");
lines.push("  if (episodeLocks[episodeId]) {");
lines.push("    const lockedProvider = episodeLocks[episodeId];");
lines.push("    console.log(`[voice-router] Episode ${episodeId} locked to provider: ${lockedProvider}`);");
lines.push("    const reordered = [lockedProvider, ...priorityList.filter(p => p !== lockedProvider)];");
lines.push("    return await attemptProviders(reordered, { text, act, channelConfig, episodeId, outputPath });");
lines.push("  }");
lines.push("  return await attemptProviders(priorityList, { text, act, channelConfig, episodeId, outputPath });");
lines.push("}");
lines.push("async function attemptProviders(providerList, { text, act, channelConfig, episodeId, outputPath }) {");
lines.push("  let lastError = null;");
lines.push("  let tier = 0;");
lines.push("  for (const providerName of providerList) {");
lines.push("    tier++;");
lines.push("    if (isCircuitOpen(providerName)) {");
lines.push("      console.log(`[voice-router] Skipping ${providerName} — circuit open`);");
lines.push("      continue;");
lines.push("    }");
lines.push("    const provider = PROVIDERS[providerName];");
lines.push("    if (!provider) {");
lines.push("      console.warn(`[voice-router] Unknown provider: ${providerName} — skipping`);");
lines.push("      continue;");
lines.push("    }");
lines.push("    // voiceId resolution -- for coqui_xtts, this is a reference-audio");
lines.push("    // path/URL (channel_dna.voice_id_coqui), not a literal voice ID. See");
lines.push("    // migrations/012_voice_tertiary.js and providers/voice/coqui-xtts.cjs's");
lines.push("    // header comment for why this field is reused for that purpose rather");
lines.push("    // than adding a differently-shaped parameter to the shared interface.");
lines.push("    const voiceId = providerName === 'elevenlabs'");
lines.push("      ? (channelConfig.voice_id_elevenlabs || channelConfig.elevenlabs_voice_id)");
lines.push("      : providerName === 'coqui_xtts'");
lines.push("        ? channelConfig.voice_id_coqui");
lines.push("        : channelConfig.voice_id_openai;");
lines.push("    const voiceParams = channelConfig.voice_params || {};");
lines.push("    console.log(`[voice-router] Attempting ${providerName} (tier ${tier}) for act ${act}...`);");
lines.push("    let result = await provider.generate({ text, voiceId, voiceParams, outputPath });");
lines.push("    if (!result.success && shouldRetry(result.statusCode)) {");
lines.push("      const delay = retryDelay(result.statusCode);");
lines.push("      console.log(`[voice-router] ${providerName} returned ${result.statusCode} — retrying after ${delay}ms`);");
lines.push("      await sleep(delay);");
lines.push("      result = await provider.generate({ text, voiceId, voiceParams, outputPath });");
lines.push("    }");
lines.push("    await logProviderEvent({");
lines.push("      episodeId, step: 'voice',");
lines.push("      act: typeof act === 'number' ? act : null,");
lines.push("      provider: providerName, tier,");
lines.push("      success: result.success,");
lines.push("      error: result.success ? null : result.error,");
lines.push("      durationMs: result.durationMs,");
lines.push("      costEstimate: result.success ? estimateCost(providerName, text.length) : null,");
lines.push("    });");
lines.push("    if (result.success) {");
lines.push("      recordSuccess(providerName);");
lines.push("      const isSubstituted = tier > 1;");
lines.push("      if (!episodeLocks[episodeId]) {");
lines.push("        episodeLocks[episodeId] = providerName;");
lines.push("        await updateEpisodeProviderFields({ episodeId, provider: providerName, substituted: isSubstituted });");
lines.push("        console.log(`[voice-router] Episode ${episodeId} locked to ${providerName}${isSubstituted ? ' (SUBSTITUTED)' : ''}`);");
lines.push("      }");
lines.push("      return result;");
lines.push("    }");
lines.push("    recordFailure(providerName);");
lines.push("    lastError = result.error;");
lines.push("    console.warn(`[voice-router] ${providerName} failed for act ${act}: ${result.error}`);");
lines.push("    if (tier < providerList.length) {");
lines.push("      console.log(`[voice-router] Failing over to next provider...`);");
lines.push("    }");
lines.push("  }");
lines.push("  const errorMsg = `All voice providers failed for act ${act}. Last error: ${lastError}`;");
lines.push("  console.error(`[voice-router] HARD FAIL: ${errorMsg}`);");
lines.push("  throw new Error(errorMsg);");
lines.push("}");
lines.push("// ── Lock management ───────────────────────────────────────────────────────────");
lines.push("function clearEpisodeLock(episodeId) {");
lines.push("  delete episodeLocks[episodeId];");
lines.push("}");
lines.push("function getEpisodeLock(episodeId) {");
lines.push("  return episodeLocks[episodeId] || null;");
lines.push("}");
lines.push("module.exports = { generateVoice, clearEpisodeLock, getEpisodeLock };");
lines.push("");

const content = lines.join('\n');
