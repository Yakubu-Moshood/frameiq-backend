const fs = require('fs');
const p = '/data/pipeline/providers/provider-router.cjs';

const lines = [];
lines.push("'use strict';");
lines.push("");
lines.push("/**");
lines.push(" * providers/provider-router.cjs");
lines.push(" * Generalized provider-fallback router for images and animation.");
lines.push(" *");
lines.push(" * This is voice-router.cjs's circuit-breaker/retry/provider_events/locking");
lines.push(" * pattern, generalized so image and animation providers can share one");
lines.push(" * mechanism instead of each having none at all (confirmed during");
lines.push(" * investigation: write-image-generator.js and write-animator.js each had a");
lines.push(" * single-shot try/catch with no fallback whatsoever, despite channel_dna");
lines.push(" * already having image_primary/secondary/tertiary and");
lines.push(" * video_primary/secondary/tertiary columns sitting unused since migration");
lines.push(" * 005). The circuit breaker, retry-before-failover, and provider_events");
lines.push(" * logging logic below is carried over from the real voice-router.cjs");
lines.push(" * essentially unchanged -- only generalized to not assume voice's specific");
lines.push(" * {text, voiceId, voiceParams, outputPath} shape.");
lines.push(" *");
lines.push(" * Provider modules here export generate(input, providerConfig) where");
lines.push(" * `input` is passed through untouched (the router doesn't know or care");
lines.push(" * what's inside it -- images and animation each define their own shape)");
lines.push(" * and `providerConfig` carries whatever per-provider config the caller");
lines.push(" * resolved from channel_dna. Same success/failure contract voice's");
lines.push(" * providers use:");
lines.push(" *   success: { success: true, path, durationMs, provider, ...extra }");
lines.push(" *   failure: { success: false, statusCode, error }");
lines.push(" *");
lines.push(" * createRouter({ step, providers, estimateCost }) returns one router");
lines.push(" * instance per step ('image' or 'video'), each with its own isolated");
lines.push(" * circuit-breaker state and episode-provider-lock map -- a failing image");
lines.push(" * provider's circuit does not affect animation's, matching how");
lines.push(" * voice-router.cjs gets that isolation implicitly by being its own module.");
lines.push(" *");
lines.push(" * Episode-level provider locking is carried over from voice for the same");
lines.push(" * reason it exists there: switching providers mid-episode is visually");
lines.push(" * jarring for images/animation (different models render in different");
lines.push(" * styles) just as it would sound jarring for voice, so once a provider");
lines.push(" * succeeds for an episode's first shot, every subsequent shot in that");
lines.push(" * episode prefers the same provider first.");
lines.push(" */");
lines.push("");
lines.push("const { v4: uuid } = require('uuid');");
lines.push("");
lines.push("const DB_MODULE_PATH = process.env.DB_MODULE_PATH || '/app/db';");
lines.push("const { run } = require(DB_MODULE_PATH);");
lines.push("");
lines.push("// ── Retry logic (identical to voice-router.cjs) ───────────────────────────────");
lines.push("const CIRCUIT_OPEN_THRESHOLD = 3;");
lines.push("const CIRCUIT_OPEN_DURATION_MS = 15 * 60 * 1000; // 15 minutes");
lines.push("const CIRCUIT_WINDOW_MS = 10 * 60 * 1000;        // 10 minutes");
lines.push("");
lines.push("function shouldRetry(statusCode) {");
lines.push("  return statusCode === 429 || statusCode === 500 || statusCode === 503 || statusCode === 0;");
lines.push("}");
lines.push("function retryDelay(statusCode) {");
lines.push("  if (statusCode === 429) return 30000;");
lines.push("  if (statusCode === 500 || statusCode === 503) return 10000;");
lines.push("  return 5000;");
lines.push("}");
lines.push("function sleep(ms) {");
lines.push("  return new Promise(resolve => setTimeout(resolve, ms));");
lines.push("}");
lines.push("");
lines.push("// ── DB logging helpers ─────────────────────────────────────────────────────────");
lines.push("async function logProviderEvent({ episodeId, step, act, shotId, provider, tier, success, error, durationMs, costEstimate }) {");
lines.push("  try {");
lines.push("    await run(`");
lines.push("      INSERT INTO provider_events (id, episode_id, step, act, shot_id, provider, tier, success, error_message, duration_ms, cost_estimate)");
lines.push("      VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?)");
lines.push("    `, [");
lines.push("      uuid(), episodeId, step, act != null ? act : null, shotId != null ? shotId : null, provider, tier,");
lines.push("      success ? 1 : 0, error || null, durationMs || null, costEstimate || null,");
lines.push("    ]);");
lines.push("  } catch (err) {");
lines.push("    console.error(`[provider-router:${step}] provider_events log failed:`, err.message);");
lines.push("  }");
lines.push("}");
lines.push("");
lines.push("// Generalizes voice-router.cjs's updateEpisodeProviderFields -- the target");
lines.push("// column is derived from step ('image' -> image_provider_used, 'video' ->");
lines.push("// video_provider_used), matching the episodes columns migration 005 already");
lines.push("// added specifically for this (previously unused -- see investigation");
lines.push("// report on the images/animation provider-fallback blind spot).");
lines.push("async function updateEpisodeProviderFields({ episodeId, step, provider, substituted }) {");
lines.push("  const columnMap = { image: 'image_provider_used', video: 'video_provider_used' };");
lines.push("  const column = columnMap[step];");
lines.push("  if (!column) return;");
lines.push("  try {");
lines.push("    await run(`");
lines.push("      UPDATE episodes");
lines.push("      SET ${column} = ?, provider_substituted = ?");
lines.push("      WHERE id = ?");
lines.push("    `, [provider, substituted ? 1 : 0, episodeId]);");
lines.push("  } catch (err) {");
lines.push("    console.error(`[provider-router:${step}] episode provider field update failed:`, err.message);");
lines.push("  }");
lines.push("}");
lines.push("");
lines.push("function createRouter({ step, providers, estimateCost }) {");
lines.push("  const circuitBreaker = {};");
lines.push("  const episodeLocks = {};");
lines.push("");
lines.push("  function getCircuit(provider) {");
lines.push("    if (!circuitBreaker[provider]) {");
lines.push("      circuitBreaker[provider] = { failures: [], openUntil: null };");
lines.push("    }");
lines.push("    return circuitBreaker[provider];");
lines.push("  }");
lines.push("  function isCircuitOpen(provider) {");
lines.push("    const circuit = getCircuit(provider);");
lines.push("    if (circuit.openUntil && Date.now() < circuit.openUntil) {");
lines.push("      console.log(`[provider-router:${step}] Circuit OPEN for ${provider} — skipping until ${new Date(circuit.openUntil).toISOString()}`);");
lines.push("      return true;");
lines.push("    }");
lines.push("    if (circuit.openUntil && Date.now() >= circuit.openUntil) {");
lines.push("      circuit.openUntil = null;");
lines.push("      console.log(`[provider-router:${step}] Circuit HALF-OPEN for ${provider} — testing`);");
lines.push("    }");
lines.push("    return false;");
lines.push("  }");
lines.push("  function recordFailure(provider) {");
lines.push("    const circuit = getCircuit(provider);");
lines.push("    const now = Date.now();");
lines.push("    circuit.failures = circuit.failures.filter(t => now - t < CIRCUIT_WINDOW_MS);");
lines.push("    circuit.failures.push(now);");
lines.push("    if (circuit.failures.length >= CIRCUIT_OPEN_THRESHOLD) {");
lines.push("      circuit.openUntil = now + CIRCUIT_OPEN_DURATION_MS;");
lines.push("      console.log(`[provider-router:${step}] Circuit OPENED for ${provider} after ${circuit.failures.length} failures`);");
lines.push("    }");
lines.push("  }");
lines.push("  function recordSuccess(provider) {");
lines.push("    const circuit = getCircuit(provider);");
lines.push("    circuit.failures = [];");
lines.push("    circuit.openUntil = null;");
lines.push("  }");
lines.push("");
lines.push("  async function run_(priorityList, { input, providerConfig, episodeId, act, shotId, costUnits, lockToEpisode = true }) {");
lines.push("    const lockedProvider = lockToEpisode ? episodeLocks[episodeId] : null;");
lines.push("    const effectiveList = lockedProvider");
lines.push("      ? [lockedProvider, ...priorityList.filter(p => p !== lockedProvider)]");
lines.push("      : priorityList;");
lines.push("");
lines.push("    if (lockedProvider) {");
lines.push("      console.log(`[provider-router:${step}] Episode ${episodeId} locked to provider: ${lockedProvider}`);");
lines.push("    }");
lines.push("");
lines.push("    let lastError = null;");
lines.push("    let tier = 0;");
lines.push("    for (const providerName of effectiveList) {");
lines.push("      tier++;");
lines.push("      if (isCircuitOpen(providerName)) {");
lines.push("        console.log(`[provider-router:${step}] Skipping ${providerName} — circuit open`);");
lines.push("        continue;");
lines.push("      }");
lines.push("      const provider = providers[providerName];");
lines.push("      if (!provider) {");
lines.push("        console.warn(`[provider-router:${step}] Unknown provider: ${providerName} — skipping`);");
lines.push("        continue;");
lines.push("      }");
lines.push("      console.log(`[provider-router:${step}] Attempting ${providerName} (tier ${tier})...`);");
lines.push("      let result = await provider.generate(input, providerConfig);");
lines.push("      if (!result.success && shouldRetry(result.statusCode)) {");
lines.push("        const delay = retryDelay(result.statusCode);");
lines.push("        console.log(`[provider-router:${step}] ${providerName} returned ${result.statusCode} — retrying after ${delay}ms`);");
lines.push("        await sleep(delay);");
lines.push("        result = await provider.generate(input, providerConfig);");
lines.push("      }");
lines.push("      await logProviderEvent({");
lines.push("        episodeId, step, act, shotId,");
lines.push("        provider: providerName, tier,");
lines.push("        success: result.success,");
lines.push("        error: result.success ? null : result.error,");
lines.push("        durationMs: result.durationMs,");
lines.push("        costEstimate: result.success ? estimateCost(providerName, costUnits) : null,");
lines.push("      });");
lines.push("      if (result.success) {");
lines.push("        recordSuccess(providerName);");
lines.push("        const isSubstituted = tier > 1;");
lines.push("        if (lockToEpisode && !episodeLocks[episodeId]) {");
lines.push("          episodeLocks[episodeId] = providerName;");
lines.push("          await updateEpisodeProviderFields({ episodeId, step, provider: providerName, substituted: isSubstituted });");
lines.push("          console.log(`[provider-router:${step}] Episode ${episodeId} locked to ${providerName}${isSubstituted ? ' (SUBSTITUTED)' : ''}`);");
lines.push("        }");
lines.push("        return result;");
lines.push("      }");
lines.push("      recordFailure(providerName);");
lines.push("      lastError = result.error;");
lines.push("      console.warn(`[provider-router:${step}] ${providerName} failed: ${result.error}`);");
lines.push("      if (tier < effectiveList.length) {");
lines.push("        console.log(`[provider-router:${step}] Failing over to next provider...`);");
lines.push("      }");
lines.push("    }");
lines.push("    const errorMsg = `All ${step} providers failed. Last error: ${lastError}`;");
lines.push("    console.error(`[provider-router:${step}] HARD FAIL: ${errorMsg}`);");
lines.push("    throw new Error(errorMsg);");
lines.push("  }");
lines.push("");
lines.push("  function clearEpisodeLock(episodeId) { delete episodeLocks[episodeId]; }");
lines.push("  function getEpisodeLock(episodeId) { return episodeLocks[episodeId] || null; }");
lines.push("");
lines.push("  return { run: run_, clearEpisodeLock, getEpisodeLock };");
lines.push("}");
lines.push("");
lines.push("module.exports = { createRouter };");
lines.push("");

const content = lines.join('\n');
fs.writeFileSync(p, content, 'utf8');
console.log('provider-router.cjs written — lines: ' + content.split('\n').length);
